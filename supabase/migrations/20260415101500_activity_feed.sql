CREATE POLICY "activity_feed_update_own"
  ON public.activity_feed
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE OR REPLACE FUNCTION public.get_activity_feed_page(
  p_user_id uuid,
  p_limit integer DEFAULT 20,
  p_cursor_created_at timestamptz DEFAULT NULL,
  p_cursor_id bigint DEFAULT NULL
)
RETURNS TABLE (
  id bigint,
  type text,
  metadata jsonb,
  seen boolean,
  created_at timestamptz
)
LANGUAGE sql
STABLE
AS $$
  SELECT af.id, af.type, af.metadata, af.seen, af.created_at
  FROM public.activity_feed af
  WHERE af.user_id = p_user_id
    AND (
      p_cursor_created_at IS NULL
      OR p_cursor_id IS NULL
      OR (af.created_at, af.id) < (p_cursor_created_at, p_cursor_id)
    )
  ORDER BY af.created_at DESC, af.id DESC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 20), 1), 100) + 1;
$$;

GRANT EXECUTE ON FUNCTION public.get_activity_feed_page(uuid, integer, timestamptz, bigint)
TO authenticated;

CREATE OR REPLACE FUNCTION public.mark_activity_feed_seen(
  p_user_id uuid,
  p_activity_ids bigint[] DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
  v_updated_count integer;
BEGIN
  IF p_activity_ids IS NULL OR cardinality(p_activity_ids) = 0 THEN
    UPDATE public.activity_feed af
    SET seen = true
    WHERE af.user_id = p_user_id
      AND af.seen = false;
  ELSE
    UPDATE public.activity_feed af
    SET seen = true
    WHERE af.user_id = p_user_id
      AND af.seen = false
      AND af.id = ANY(p_activity_ids);
  END IF;

  GET DIAGNOSTICS v_updated_count = ROW_COUNT;
  RETURN v_updated_count;
END;
$$;

GRANT EXECUTE ON FUNCTION public.mark_activity_feed_seen(uuid, bigint[])
TO authenticated;

CREATE OR REPLACE FUNCTION public.insert_activity_for_expense_event(
  p_event_type text,
  p_expense_row jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_expense_id uuid := NULLIF(p_expense_row ->> 'id', '')::uuid;
  v_group_id uuid := NULLIF(p_expense_row ->> 'group_id', '')::uuid;
  v_created_by uuid := NULLIF(p_expense_row ->> 'created_by', '')::uuid;
  v_paid_by uuid := NULLIF(p_expense_row ->> 'paid_by', '')::uuid;
  v_metadata jsonb;
  v_inserted_count integer := 0;
BEGIN
  IF v_expense_id IS NULL THEN
    RETURN;
  END IF;

  v_metadata := jsonb_build_object(
    'expense_id', v_expense_id,
    'group_id', v_group_id,
    'created_by', v_created_by,
    'paid_by', v_paid_by,
    'amount', p_expense_row -> 'amount',
    'currency', p_expense_row -> 'currency',
    'description', p_expense_row -> 'description',
    'category', p_expense_row -> 'category'
  );

  IF to_regclass('public.expense_splits') IS NOT NULL THEN
    EXECUTE
      'INSERT INTO public.activity_feed (user_id, type, metadata)
       SELECT DISTINCT es.user_id, $1, $2
       FROM public.expense_splits es
       WHERE es.expense_id = $3
         AND es.user_id IS NOT NULL'
    USING p_event_type, v_metadata, v_expense_id;

    GET DIAGNOSTICS v_inserted_count = ROW_COUNT;
  END IF;

  IF v_inserted_count = 0
    AND v_group_id IS NOT NULL
    AND to_regclass('public.group_members') IS NOT NULL THEN
    EXECUTE
      'INSERT INTO public.activity_feed (user_id, type, metadata)
       SELECT DISTINCT gm.user_id, $1, $2
       FROM public.group_members gm
       WHERE gm.group_id = $3
         AND gm.user_id IS NOT NULL'
    USING p_event_type, v_metadata, v_group_id;
  END IF;
END;
$$;

