CREATE TABLE IF NOT EXISTS public.activity_feed (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  type text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  seen boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT activity_feed_type_check CHECK (
    type IN ('expense_created', 'expense_deleted', 'settlement_created')
  )
);

CREATE INDEX IF NOT EXISTS idx_activity_feed_user_created_desc
  ON public.activity_feed (user_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_activity_feed_user_seen_created_desc
  ON public.activity_feed (user_id, seen, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_activity_feed_user_unseen_desc
  ON public.activity_feed (user_id, created_at DESC, id DESC)
  WHERE seen = false;

ALTER TABLE public.activity_feed ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "activity_feed_select_own" ON public.activity_feed;
DROP POLICY IF EXISTS "activity_feed_update_own" ON public.activity_feed;

CREATE POLICY "activity_feed_select_own"
  ON public.activity_feed
  FOR SELECT
  TO authenticated
