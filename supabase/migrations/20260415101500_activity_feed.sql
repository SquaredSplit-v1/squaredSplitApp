CREATE OR REPLACE FUNCTION public.activity_feed_on_settlement_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_settlement_row jsonb := to_jsonb(NEW);
  v_from_user uuid := NULLIF(v_settlement_row ->> 'from_user', '')::uuid;
  v_to_user uuid := NULLIF(v_settlement_row ->> 'to_user', '')::uuid;
  v_metadata jsonb;
BEGIN
  v_metadata := jsonb_build_object(
    'settlement_id', v_settlement_row -> 'id',
    'group_id', v_settlement_row -> 'group_id',
    'from_user', v_settlement_row -> 'from_user',
    'to_user', v_settlement_row -> 'to_user',
    'amount', v_settlement_row -> 'amount',
    'currency', v_settlement_row -> 'currency',
    'status', v_settlement_row -> 'status'
  );

  INSERT INTO public.activity_feed (user_id, type, metadata)
  SELECT DISTINCT participant.user_id, 'settlement_created', v_metadata
  FROM (
    VALUES (v_from_user), (v_to_user)
  ) AS participant(user_id)
  WHERE participant.user_id IS NOT NULL;

  RETURN NEW;
END;
$$;

